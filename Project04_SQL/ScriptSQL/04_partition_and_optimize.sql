-- Đồng bộ identity sequences sau khi chèn ID có sẵn.
SELECT setval(
    pg_get_serial_sequence('"order"', 'order_id'),
    (SELECT max(order_id) FROM "order"),
    true
);

SELECT setval(
    pg_get_serial_sequence('order_item', 'order_item_id'),
    (SELECT max(order_item_id) FROM order_item),
    true
);

-- Index bắt buộc theo đề và các index hỗ trợ report/join.
CREATE INDEX idx_order_item_product_id
    ON order_item(product_id);

CREATE INDEX idx_order_item_order_id_date
    ON order_item(order_id, order_date);

CREATE INDEX idx_order_status_date
    ON "order"(status, order_date);

CREATE INDEX idx_order_total_amount_desc
    ON "order"(total_amount DESC);

CREATE INDEX IF NOT EXISTS idx_product_seller_product
    ON product(seller_id, product_id);

CREATE INDEX IF NOT EXISTS idx_product_brand_product
    ON product(brand_id, product_id);

CREATE INDEX IF NOT EXISTS idx_product_category_product
    ON product(category_id, product_id);

ANALYZE "order";
ANALYZE order_item;
ANALYZE product;

-- Kiểm tra partition routing.
SELECT
    tableoid::regclass AS partition_name,
    count(*) AS row_count
FROM "order"
GROUP BY tableoid
ORDER BY partition_name::text;

SELECT
    tableoid::regclass AS partition_name,
    count(*) AS row_count
FROM order_item
GROUP BY tableoid
ORDER BY partition_name::text;
